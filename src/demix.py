#!/usr/bin/env python3
"""Recurrent-versus-input demix read-outs for population trajectory data.

This module provides two complementary read-outs that quantify how much of a
population's moment-to-moment change is generated by its own recurrence versus
driven by a known external input. Both take

    X : array (ntrials, T, F)  state trajectories
    U : array (ntrials, T, c)  known exogenous input, aligned to X.

Read-outs:

  sdmdc_dom(X, U)      -> magnitude of the dominant eigenvalue of the latent
                          autonomous operator A_v, estimated with canonical
                          SubspaceDMDc (N4SID). It recovers the true autonomous
                          gain invariant to input strength when the input is
                          exogenous (not a function of state); it is unreliable
                          when the input is strongly state-correlated.

  autonomy_index(X, U) -> variance partition. auto_unique = R2(x'|x,u) - R2(x'|u)
                          is the next-state variance explained by the past state
                          beyond the known input (the recurrence contribution).
                          Robust to eigenvalue blow-up and comparable across
                          datasets. Returns r2_full / r2_input / r2_auto,
                          auto_unique, input_unique, and a normalized
                          autonomy_index in [-1, 1].
"""
import warnings
warnings.filterwarnings("ignore")
import numpy as np

def to_np(M):
    return np.asarray(M.cpu() if hasattr(M, "cpu") else M)

# ---------- canonical SubspaceDMDc autonomous recurrence ----------
def sdmdc_dom(X, U, rank=None, nd=2):
    """dom|lambda| of the latent autonomous operator A_v (SubspaceDMDc/N4SID)."""
    from DSA import SubspaceDMDc
    F = X.shape[2]
    if rank is None:
        rank = F
    try:
        d = SubspaceDMDc(X, control_data=U, n_delays=nd, rank=rank, device="cpu", verbose=False)
        d.fit()
        Av = to_np(d.A_v)
        return float(np.max(np.abs(np.linalg.eigvals(Av))))
    except Exception:
        return np.nan

# ---------- variance-partition autonomy index (robust, cross-dataset) ----------
def _ridge_mvr2(P, Y, lam=1e-2):
    """multivariate fraction-of-variance-explained for ridge predictor P->Y (in-sample).
    Scale-aware ridge + pinv fallback; standardizes predictors; guards non-finite rows."""
    P = np.asarray(P, float); Y = np.asarray(Y, float)
    good = np.isfinite(P).all(1) & np.isfinite(Y).all(1)
    P, Y = P[good], Y[good]
    if len(P) < P.shape[1] + 2:
        return np.nan
    mu = P.mean(0); sd = P.std(0); sd[sd < 1e-9] = 1.0
    Ps = (P - mu) / sd
    Pa = np.column_stack([Ps, np.ones(len(Ps))])
    G = Pa.T @ Pa
    ridge = lam * (np.trace(G) / G.shape[0])
    try:
        W = np.linalg.solve(G + ridge*np.eye(G.shape[0]), Pa.T @ Y)
    except np.linalg.LinAlgError:
        W = np.linalg.pinv(G + ridge*np.eye(G.shape[0])) @ (Pa.T @ Y)
    pred = Pa @ W
    ss_res = float(np.sum((Y-pred)**2))
    ss_tot = float(np.sum((Y-Y.mean(0))**2)) + 1e-12
    return 1.0 - ss_res/ss_tot

def autonomy_index(X, U, lam=1e-2, cv=False):
    """variance partition of next-state predictability into recurrence vs known-input."""
    Xt, Xn, Ut = [], [], []
    for xi, ui in zip(X, U):
        if len(xi) < 2:
            continue
        Xt.append(xi[:-1]); Xn.append(xi[1:]); Ut.append(ui[:-1])
    if not Xt:
        return dict(autonomy_index=np.nan, auto_unique=np.nan, input_unique=np.nan,
                    r2_full=np.nan, r2_input=np.nan, r2_auto=np.nan)
    Xt = np.concatenate(Xt); Xn = np.concatenate(Xn); Ut = np.concatenate(Ut)
    if cv:
        # 5-fold CV R2 (guards against count-driven overfit differences)
        def cv_r2(P, Y):
            n = len(P); idx = np.arange(n); rng = np.random.default_rng(0); rng.shuffle(idx)
            folds = np.array_split(idx, 5); preds = np.zeros_like(Y);
            for k in range(5):
                te = folds[k]; tr = np.concatenate([folds[j] for j in range(5) if j != k])
                Pa = np.column_stack([P[tr], np.ones(len(tr))])
                W = np.linalg.solve(Pa.T@Pa+lam*np.eye(Pa.shape[1]), Pa.T@Y[tr])
                preds[te] = np.column_stack([P[te], np.ones(len(te))])@W
            ss_res = float(np.sum((Y-preds)**2)); ss_tot = float(np.sum((Y-Y.mean(0))**2))+1e-12
            return 1.0-ss_res/ss_tot
        r2_full = cv_r2(np.column_stack([Xt, Ut]), Xn)
        r2_input = cv_r2(Ut, Xn); r2_auto = cv_r2(Xt, Xn)
    else:
        r2_full = _ridge_mvr2(np.column_stack([Xt, Ut]), Xn, lam)
        r2_input = _ridge_mvr2(Ut, Xn, lam); r2_auto = _ridge_mvr2(Xt, Xn, lam)
    auto_unique = r2_full - r2_input      # recurrence beyond known input
    input_unique = r2_full - r2_auto      # input beyond recurrence
    idx = auto_unique/(abs(auto_unique)+abs(input_unique)+1e-9)
    return dict(autonomy_index=float(idx), auto_unique=float(auto_unique),
                input_unique=float(input_unique), r2_full=float(r2_full),
                r2_input=float(r2_input), r2_auto=float(r2_auto))
